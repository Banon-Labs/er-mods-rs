//! The 2.7.2.0 rvas a constant detour may target.
//!
//! [`crate::game_build::resolve_detour_address`] answers `Some` for a game-image address only when
//! its rva is in this list. Being the right address and being a safe place for MinHook to write
//! five bytes are different claims: a call or a read needs the first, a detour needs both. Every
//! row here is a function whose body was compared instruction by instruction across two builds
//! and found the same, with both images agreeing on where it starts, before the workspace moved to
//! 2.7.2.0 -- the verdict on each line is that comparison's. A data global, a vtable, a function
//! paired only by its masked signature, and the two three-byte leaves too short to patch are
//! absent on purpose, so they stay callable and readable but never hookable.
//!
//! Measured 2026-08-29 when weaker rows were allowed to carry detours: er-armament-icons installed
//! five of them and the game died 2 seconds into boot. That is the crash this list exists to stop.
//!
//! The 535 rows are the detour-safe set carried to 2.7.2.0 when the workspace moved to native
//! addresses on 2026-10-23: the former `DETOUR_SAFE` rows of the 1.16.2 -> 1.17 -> 2.7.2.0 carry,
//! each written here as its 2.7.2.0 destination with the comparison's verdict beside it. The list
//! is kept by hand from now on.
//!
//! A new detour target is added by measuring it on `eldenring-deobf-1.17.2.bin` -- a `.pdata`
//! entry that starts at it, and a prologue long enough to relocate -- and adding its line here, in
//! ascending order, because the resolver binary-searches the list (a unit test in `game_build.rs`
//! fails when it is not strictly ascending). `scripts/classify-entry-kind.py --fail-on-mid` and
//! `scripts/audit-hook-targets.py` check every row against that image. A hook on an address found
//! at runtime belongs on `er_hook`'s `*_runtime_derived` entry points instead, which audit the live
//! `.pdata` and need no row.

