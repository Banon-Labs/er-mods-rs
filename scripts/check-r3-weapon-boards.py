#!/usr/bin/env python3
"""Are the R3 weapon boards stale, and does that block this change?

    python3 scripts/check-r3-weapon-boards.py              # the check.sh step
    python3 scripts/check-r3-weapon-boards.py --paths a b  # as if the diff were exactly a and b
    python3 scripts/check-r3-weapon-boards.py --strict     # block whatever the diff is
    python3 scripts/check-r3-weapon-boards.py --rev <ref>  # print the decision for another commit
    python3 scripts/check-r3-weapon-boards.py --selftest

The boards are the content of the er-r3-view DLL, generated by `scripts/gen-r3-weapon-boards.py`,
and `gen-r3-weapon-boards.py --check` calls them stale when any of the ~3000 inputs recorded in
`crates/er-r3-view/src/weapon_boards.inputs` changed -- every mechanics script among them. A
regeneration is hours, so that check blocks only a change that touches what ships the boards:
`crates/er-r3-view/**` (the module and its `.inputs` included) or the generator itself
(`BLOCKING_SCOPES["r3-weapon-boards"]` in `scripts/check-stages.py`, whose selftest covers the
selection). Any other change, a mechanics-script edit included, gets one line naming how many inputs
changed and the regeneration command, and exit 0.

Which paths count. The paths changed by the commits no remote has yet: the union of each
commit's diff against its first parent over `git rev-list <rev> --not --remotes`, plus the working
tree when the subject is `HEAD`. A commit already on a remote branch already passed this gate
there, and branches stacked on an unmerged board regeneration (cabbf277, on
`origin/feat/build-kit-consumables-crit-row` and not on main) would otherwise carry that
regeneration's `weapon_boards.rs` in every merge-base diff and block forever. When no commit is
unpushed (CI, where the pull request is already on the remote) or there are more than
`MAX_UNPUSHED` of them (no remote-tracking refs at all), the paths are the diff against
`merge-base(origin/main, <rev>)` instead, the same diff `check-stages.py`'s stage selection reads.
A diff that cannot be resolved blocks, the safe direction for a gate.
"""

from __future__ import annotations

import argparse
import importlib.util
import subprocess
import sys
import tempfile
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
SCOPE = "r3-weapon-boards"
REGEN = "python3 scripts/gen-r3-weapon-boards.py --jobs 3"
#: More unpushed commits than this means the remote-tracking refs are missing or useless (a fresh
#: clone with no fetch), and the merge-base diff is the better question.
MAX_UNPUSHED = 200
GIT_SECONDS = 20


def git(cwd: Path, *args: str) -> str:
    return subprocess.run(["git", "-C", str(cwd), *args], capture_output=True, text=True, check=True,
                          timeout=GIT_SECONDS).stdout


def _lines(text: str) -> set[str]:
    return {line.strip() for line in text.splitlines() if line.strip()}


def changed_paths(cwd: Path, base: str, rev: str | None) -> tuple[list[str], str]:
    """(changed paths, which question produced them). Raises when git cannot answer."""
    subject = rev or "HEAD"
    commits = git(cwd, "rev-list", subject, "--not", "--remotes").split()
    paths: set[str] = set()
    if rev is None:
        paths |= _lines(git(cwd, "diff", "--name-only", "HEAD"))
        paths |= _lines(git(cwd, "ls-files", "--others", "--exclude-standard"))
    if 0 < len(commits) <= MAX_UNPUSHED:
        for commit in commits:
            paths |= _lines(git(cwd, "diff-tree", "-m", "--first-parent", "--no-commit-id",
                                "--name-only", "-r", commit))
        return sorted(paths), f"{len(commits)} commit(s) no remote has"
    merge_base = git(cwd, "merge-base", base, subject).strip()
    paths |= _lines(git(cwd, "diff", "--name-only", merge_base, subject))
    why = "no unpushed commit" if not commits else f"{len(commits)} unpushed commits, over {MAX_UNPUSHED}"
    return sorted(paths), f"{why}, so the diff against merge-base({base}, {subject})"


def _load(name: str, rel: str):
    spec = importlib.util.spec_from_file_location(name, REPO / rel)
    if spec is None or spec.loader is None:
        raise SystemExit(f"check-r3-weapon-boards: cannot load {rel}")
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


def advisory_line(rel_out: str, why: list[str], reason: str) -> str:
    return (f"check-r3-weapon-boards: {rel_out} is stale, {len(why)} input(s) changed since it was "
            f"generated -- not blocking, {reason}. Regenerate with: {REGEN}")


def decide(stages, paths: list[str] | None, base: str, rev: str | None = None,
           cwd: Path = REPO) -> tuple[bool, str]:
    source = "the given paths"
    if paths is None:
        try:
            paths, source = changed_paths(cwd, base, rev)
        except Exception as err:  # noqa: BLE001 -- an unknown diff has one answer: block
            return True, f"the diff against {base} cannot be resolved ({type(err).__name__}: {err})"
    blocking, why = stages.blocks_for_paths(SCOPE, paths)
    return blocking, f"{why} (paths from {source})"


def run(paths: list[str] | None, base: str, strict: bool, rev: str | None) -> int:
    stages = _load("er_check_stages_for_boards", "scripts/check-stages.py")
    blocking, reason = (True, "--strict") if strict else decide(stages, paths, base, rev)
    if rev is not None:
        # A decision about another commit; the board files in this tree are not that commit's.
        print(f"check-r3-weapon-boards: {rev}: {'blocking' if blocking else 'not blocking'}, {reason}")
        return 0
    gen = _load("er_gen_r3_weapon_boards", "scripts/gen-r3-weapon-boards.py")
    if blocking:
        print(f"check-r3-weapon-boards: blocking, {reason}")
        return gen.check()
    if not gen.OUT_RS.exists() or not gen.OUT_INPUTS.exists():
        why = [f"{gen.REL_OUT} or {gen.REL_INPUTS} is missing"]
    else:
        why, _, _ = gen.staleness(gen.OUT_RS.read_text(), gen.OUT_INPUTS.read_text())
    if why:
        print(advisory_line(gen.REL_OUT, why, reason))
    else:
        print(f"check-r3-weapon-boards: {gen.REL_OUT} is current (not blocking, {reason})")
    return 0


def selftest() -> int:
    stages = _load("er_check_stages_for_boards", "scripts/check-stages.py")
    assert decide(stages, ["scripts/er-mechanics-combo-loadout.py"], "origin/main")[0] is False
    assert decide(stages, ["crates/er-r3-view/src/lib.rs"], "origin/main")[0] is True
    assert decide(stages, ["scripts/gen-r3-weapon-boards.py"], "origin/main")[0] is True
    blocked, why = decide(stages, None, "origin/main", "no-such-ref/xyz")
    assert blocked and "cannot be resolved" in why, why
    line = advisory_line("crates/er-r3-view/src/weapon_boards.rs",
                         ["source scripts/a.py changed", "source scripts/b.py changed"],
                         "this diff changes none of x")
    assert "\n" not in line and "2 input(s) changed" in line and REGEN in line, line
    stacked_selftest(stages)
    print("selftest ok: the board check blocks on er-r3-view and generator changes, reports "
          "otherwise, blocks when the diff is unknown, and ignores a stacked base already on a remote")
    return 0


def stacked_selftest(stages) -> None:
    """A branch stacked on a remote-only board regeneration, in a throwaway repository.

    main (origin/main) <- R: regenerates er-r3-view (origin/feat, not on main) <- L: local."""
    with tempfile.TemporaryDirectory() as tmp:
        repo = Path(tmp)
        cfg = ("-c", "user.name=t", "-c", "user.email=t@t", "-c", "commit.gpgsign=false",
               "-c", "core.hooksPath=/dev/null")

        def commit(rel: str, text: str) -> str:
            path = repo / rel
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
            git(repo, "add", rel)
            git(repo, *cfg, "commit", "-q", "-m", rel)
            return git(repo, "rev-parse", "HEAD").strip()

        git(repo, "init", "-q", "-b", "main")
        base = commit("README", "base\n")
        git(repo, "update-ref", "refs/remotes/origin/main", base)
        regen = commit("crates/er-r3-view/src/weapon_boards.rs", "boards\n")
        git(repo, "update-ref", "refs/remotes/origin/feat", regen)
        commit("scripts/er-mechanics-ar.py", "x = 1\n")

        def blocks(rev: str | None = None) -> tuple[bool, str]:
            return decide(stages, None, "origin/main", rev, repo)

        got = blocks()
        assert got[0] is False and "1 commit(s) no remote has" in got[1], got
        assert blocks("HEAD")[0] is False
        # Every commit pushed: the merge-base diff still carries the regeneration, so it blocks.
        assert blocks("origin/feat")[0] is True, blocks("origin/feat")
        # A local commit that touches er-r3-view itself blocks.
        commit("crates/er-r3-view/src/lib.rs", "// x\n")
        assert blocks()[0] is True, blocks()
        # ...and so does an uncommitted er-r3-view edit in the working tree.
        git(repo, "reset", "-q", "--hard", "HEAD~1")
        (repo / "crates/er-r3-view/src/weapon_boards.rs").write_text("edited\n")
        assert blocks()[0] is True, blocks()


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--paths", nargs="*", help="decide for these changed paths instead of the diff")
    ap.add_argument("--base", default="origin/main", help="diff base (default: origin/main)")
    ap.add_argument("--strict", action="store_true", help="block on stale boards whatever the diff")
    ap.add_argument("--rev", help="only print the decision for this commit or branch (read-only; "
                                  "checks out nothing, compares no board files)")
    ap.add_argument("--selftest", action="store_true")
    a = ap.parse_args()
    if a.selftest:
        return selftest()
    return run(a.paths, a.base, a.strict, a.rev)


if __name__ == "__main__":
    sys.exit(main())
