#!/usr/bin/env python3
"""Edit the duel rules referee's rules file from a terminal: switch any built-in rule off, change
its numbers, and add bans of your own built from anything in the game.

    python3 scripts/er-duel-rules-bans.py show
    python3 scripts/er-duel-rules-bans.py find katana
    python3 scripts/er-duel-rules-bans.py ban "No 2H Rivers" weapon="Rivers of Blood" where=twoHanded
    python3 scripts/er-duel-rules-bans.py ban "Bleed katanas with Lord of Blood" \\
        class=Katana affinity=Blood talisman="Lord of Blood's Exultation"
    python3 scripts/er-duel-rules-bans.py ban "No Comet Azur" spell="Comet Azur"
    python3 scripts/er-duel-rules-bans.py ban "Arcane over 45" "stat=Arcane >= 45"
    python3 scripts/er-duel-rules-bans.py off LightRoll        # a built-in rule, or a ban, by name
    python3 scripts/er-duel-rules-bans.py on LightRoll
    python3 scripts/er-duel-rules-bans.py set runeLevel 150
    python3 scripts/er-duel-rules-bans.py unban "No Comet Azur"

The file is er-duel-rules.json beside eldenring.exe (`ER_GAME_DIR`, else this machine's Steam
install; `--file` names another). The Frida agent and the Cheat Engine table read it again within
two seconds of a change, so a running referee picks an edit up without a restart. The Cheat
Engine table's Rules window edits the same file with a picker.

A ban breaks when every condition holds for one player at once; a condition is one `kind=value`
term, and `|` inside a value lists alternatives, any one of which will do. `where=`, `buff=yes`,
`class=` and `affinity=` narrow the weapon condition before them (or make one). Kinds that take
names: weapon, class, affinity, armor, talisman, tear, skill, spell, item. Kinds that take ids,
separated by commas: effect, bullet, anim. `level=` and `stat=` take a comparison: `level=!= 125`,
`stat=Arcane >= 45`. A weapon's `where` is one of equipped (any slot, the default), held, right,
left, twoHanded, oneHanded, powerstanced, skill (the weapon a skill came from).

Names come from the catalog the Frida agent carries (scripts/frida/er-duel-rules.js, generated by
scripts/er-duel-rules-gen.py), so they are the game's own and an unknown one is refused with the
nearest it does know.
"""

import argparse
import difflib
import json
import os
import pathlib
import re
import shutil
import subprocess
import sys
import tempfile

HERE = pathlib.Path(__file__).resolve().parent
AGENT = HERE / 'frida' / 'er-duel-rules.js'
RULES_FILE_NAME = 'er-duel-rules.json'
GAME_DIR = pathlib.Path(os.environ.get(
    'ER_GAME_DIR', pathlib.Path.home() / '.local/share/Steam/steamapps/common/ELDEN RING/Game'))
# The agent's defaults, which an absent file means.
DEFAULTS = {'off': [], 'runeLevel': 125, 'blueFlasks': 2, 'shieldGuardCap': 90, 'bans': []}
SETTINGS = ('runeLevel', 'blueFlasks', 'shieldGuardCap')
WHERE = ('equipped', 'held', 'right', 'left', 'twoHanded', 'oneHanded', 'powerstanced', 'skill')
COMPARE = ('!=', '<=', '>=', '=', '<', '>')
ATTRIBUTES = ('Vigor', 'Mind', 'Endurance', 'Strength', 'Dexterity', 'Intelligence', 'Faith', 'Arcane')
# Each kind of name, the catalog list it comes from and the condition field it fills.
NAMED = {
    'weapon': ('weapons', 'weapon', 'items'), 'class': ('classes', 'weapon', 'classes'),
    'affinity': ('affinities', 'weapon', 'affinities'), 'armor': ('armor', 'armor', 'items'),
    'talisman': ('talismans', 'talisman', 'items'), 'tear': ('tears', 'tear', 'items'),
    'skill': ('skills', 'skill', 'items'), 'spell': ('spells', 'spell', 'items'),
    'item': ('items', 'item', 'items'),
}
RAW = ('effect', 'bullet', 'anim')


def agent_block(name: str) -> dict:
    """A generated `const <name> = {...};` line out of the agent, as data."""
    for line in AGENT.read_text(encoding='utf-8').splitlines():
        if line.startswith(f'const {name} = '):
            return json.loads(line[len(f'const {name} = '):].rstrip(';'))
    raise SystemExit(f'{AGENT} has no {name}; rerun scripts/er-duel-rules-gen.py --write')


def rule_names() -> dict:
    """The built-in rules, key -> wording, read from the agent's RULE_TEXT."""
    text = AGENT.read_text(encoding='utf-8')
    block = text[text.index('const RULE_TEXT = {'):]
    block = block[:block.index('\n};')]
    return {k: v for k, v in re.findall(r"^\s+(\w+): ['\"](.*)['\"],$", block, re.M)}


def entry(list_name: str, row: list) -> dict:
    if list_name == 'weapons':
        return {'name': row[0], 'ids': row[2], 'bullets': [], 'effects': []}
    if list_name in ('classes', 'affinities'):
        return {'name': row[0], 'ids': [row[1]], 'bullets': [], 'effects': []}
    if list_name in ('spells', 'items'):
        return {'name': row[0], 'ids': [], 'bullets': row[1], 'effects': row[2]}
    return {'name': row[0], 'ids': row[1], 'bullets': [], 'effects': []}


def pick(catalog: dict, kind: str, name: str) -> dict:
    list_name = NAMED[kind][0]
    rows = catalog[list_name]
    for row in rows:
        if row[0].lower() == name.strip().lower():
            return entry(list_name, row)
    near = difflib.get_close_matches(name, [r[0] for r in rows], n=3, cutoff=0.5)
    hint = f'; did you mean {" or ".join(repr(n) for n in near)}?' if near else f'; try: find {name!r}'
    raise SystemExit(f'no {kind} is called {name!r}{hint}')


def conditions(catalog: dict, terms: list) -> list:
    """The conditions `kind=value` terms describe, in order."""
    out = []
    weapon = None
    for term in terms:
        kind, sep, value = term.partition('=')
        kind = kind.strip()
        if not sep:
            raise SystemExit(f'{term!r} is not kind=value')
        if kind in ('where', 'buff') or (kind in ('class', 'affinity') and weapon is not None):
            if weapon is None:
                weapon = {'kind': 'weapon', 'items': [], 'classes': [], 'affinities': [],
                          'where': 'equipped', 'buff': False}
                out.append(weapon)
            if kind == 'where':
                if value not in WHERE:
                    raise SystemExit(f'where is one of {", ".join(WHERE)}')
                weapon['where'] = value
            elif kind == 'buff':
                weapon['buff'] = value.lower() in ('yes', 'true', '1', 'on')
            else:
                weapon[NAMED[kind][2]] += [pick(catalog, kind, n) for n in value.split('|')]
            continue
        if kind in NAMED:
            _, cond_kind, field = NAMED[kind]
            c = {'kind': cond_kind, 'items': []}
            if cond_kind == 'weapon':
                c.update(classes=[], affinities=[], where='equipped', buff=False)
                weapon = c
            else:
                weapon = None
            c[field] = [pick(catalog, kind, n) for n in value.split('|')]
            out.append(c)
        elif kind in RAW:
            ids = [int(x) for x in re.findall(r'-?\d+', value)]
            if not ids:
                raise SystemExit(f'{term!r} names no ids')
            out.append({'kind': kind, 'items': [{'name': f'{kind} {i}', 'ids': [i], 'bullets': [],
                                                 'effects': []} for i in ids]})
            weapon = None
        elif kind in ('level', 'stat'):
            c = {'kind': kind}
            rest = value
            if kind == 'stat':
                m = re.match(r'^\s*([A-Za-z]+)\s*(.*)$', value)
                match = [i for i, a in enumerate(ATTRIBUTES) if m and a.lower() == m.group(1).lower()]
                if not match:
                    raise SystemExit(f'stat= starts with one of {", ".join(ATTRIBUTES)}')
                c['stat'], rest = match[0], m.group(2)
            m = re.match(r'^\s*(!=|<=|>=|=|<|>)\s*(-?\d+(?:\.\d+)?)\s*$', rest)
            if not m:
                raise SystemExit(f'{term!r}: write a comparison and a number, such as "!= 125"')
            number = float(m.group(2))
            c['op'], c['value'] = m.group(1), int(number) if number.is_integer() else number
            out.append(c)
            weapon = None
        else:
            raise SystemExit(f'no condition kind {kind!r}; see --help')
    return out


def load(path: pathlib.Path) -> dict:
    if not path.exists():
        return json.loads(json.dumps(DEFAULTS))
    cfg = json.loads(path.read_text(encoding='utf-8'))
    for k, v in DEFAULTS.items():
        cfg.setdefault(k, json.loads(json.dumps(v)))
    return cfg


def save(path: pathlib.Path, cfg: dict) -> None:
    text = json.dumps({k: cfg[k] for k in DEFAULTS}, indent=2, ensure_ascii=False) + '\n'
    tmp = path.with_name(path.name + '.tmp')
    tmp.write_text(text, encoding='utf-8')
    os.replace(tmp, path)


def describe(c: dict) -> str:
    if c['kind'] == 'level':
        return f'rune level {c["op"]} {c["value"]}'
    if c['kind'] == 'stat':
        return f'{ATTRIBUTES[c["stat"]]} {c["op"]} {c["value"]}'
    parts = [' or '.join(e['name'] for e in c.get('items', []))] if c.get('items') else []
    for field in ('classes', 'affinities'):
        if c.get(field):
            parts.append(f'{field[:-2] if field == "classes" else "affinity"} '
                         + ' or '.join(e['name'] for e in c[field]))
    if c['kind'] == 'weapon':
        if not parts:
            parts.append('any weapon')
        if c.get('where', 'equipped') != 'equipped':
            parts.append(c['where'])
        if c.get('buff'):
            parts.append('with a weapon buff')
    return f'{c["kind"]}: {", ".join(parts)}'


def show(cfg: dict, rules: dict) -> str:
    lines = ['Built-in rules:']
    for key, text in rules.items():
        for setting, rule in zip(SETTINGS, ('RuneLevel', 'CeruleanFlasks', 'ShieldGuard')):
            if key == rule:
                text = re.sub(r'\d+', str(cfg[setting]), text, count=1)
        lines.append(f'  [{" " if key in cfg["off"] else "x"}] {key}: {text}')
    lines.append('Bans of your own:')
    for b in cfg['bans']:
        lines.append(f'  [{"x" if b.get("on", True) else " "}] {b["name"]}: '
                     + '  AND  '.join(describe(c) for c in b['all']))
    if not cfg['bans']:
        lines.append('  (none)')
    return '\n'.join(lines)


def run(argv: list, path: pathlib.Path) -> str:
    catalog, rules = agent_block('CATALOG'), rule_names()
    cmd, args = argv[0], argv[1:]
    cfg = load(path)
    if cmd == 'show':
        return show(cfg, rules)
    if cmd == 'find':
        needle = ' '.join(args).lower()
        hits = [f'{kind}={row[0]!r}' for kind, (list_name, _, _) in NAMED.items()
                for row in catalog[list_name] if needle in row[0].lower()]
        return '\n'.join(hits[:80]) or 'nothing by that name'
    if cmd == 'ban':
        if len(args) < 2:
            raise SystemExit('ban NAME kind=value ...')
        name = args[0].strip()
        cfg['bans'] = [b for b in cfg['bans'] if b['name'] != name]
        cfg['bans'].append({'name': name, 'on': True, 'all': conditions(catalog, args[1:])})
    elif cmd == 'unban':
        before = len(cfg['bans'])
        cfg['bans'] = [b for b in cfg['bans'] if b['name'] != ' '.join(args)]
        if len(cfg['bans']) == before:
            raise SystemExit(f'no ban is called {" ".join(args)!r}')
    elif cmd in ('on', 'off'):
        name = ' '.join(args)
        key = next((k for k, t in rules.items() if name.lower() in (k.lower(), t.lower())), None)
        bans = [b for b in cfg['bans'] if b['name'] == name]
        if key is not None:
            cfg['off'] = [k for k in cfg['off'] if k != key] + ([key] if cmd == 'off' else [])
        elif bans:
            for b in bans:
                b['on'] = cmd == 'on'
        else:
            raise SystemExit(f'no rule or ban is called {name!r}; `show` lists them')
    elif cmd == 'set':
        if len(args) != 2 or args[0] not in SETTINGS:
            raise SystemExit(f'set one of {", ".join(SETTINGS)} to a number')
        number = float(args[1])
        if number < 0:
            raise SystemExit('the number must be 0 or more')
        cfg[args[0]] = int(number) if number.is_integer() else number
    else:
        raise SystemExit(f'no command {cmd!r}; see --help')
    save(path, cfg)
    return f'wrote {path}\n' + show(cfg, rules)


def selftest() -> int:
    """Edits a scratch file the way the examples do, and has the Frida agent read it back."""
    with tempfile.TemporaryDirectory() as d:
        path = pathlib.Path(d) / RULES_FILE_NAME
        run(['ban', 'No 2H Rivers', 'weapon=Rivers of Blood', 'where=twoHanded'], path)
        run(['ban', 'Bleed katanas', 'class=Katana', 'affinity=Blood', 'buff=yes',
             "talisman=Lord of Blood's Exultation"], path)
        run(['ban', 'Arcane', 'stat=Arcane >= 45', 'level=!= 125', 'effect=3310, 3314'], path)
        run(['off', 'Light Roll (<30% Equip Load)'], path)
        run(['off', 'No 2H Rivers'], path)
        run(['set', 'runeLevel', '150'], path)
        cfg = load(path)
        assert cfg['off'] == ['LightRoll'] and cfg['runeLevel'] == 150, cfg
        assert [b['on'] for b in cfg['bans']] == [False, True, True], cfg['bans']
        katana = cfg['bans'][1]['all']
        assert katana[0]['classes'][0]['ids'] == [13] and katana[0]['affinities'][0]['ids'] == [1100]
        assert katana[0]['buff'] is True and katana[1]['kind'] == 'talisman', katana
        arcane = cfg['bans'][2]['all']
        assert arcane[0] == {'kind': 'stat', 'stat': 7, 'op': '>=', 'value': 45}, arcane
        assert arcane[1] == {'kind': 'level', 'op': '!=', 'value': 125}, arcane
        for bad in (['ban', 'x', 'weapon=Not A Weapon'], ['ban', 'x', 'where=up'], ['set', 'size', '1']):
            try:
                run(bad, path)
            except SystemExit:
                continue
            raise AssertionError(f'{bad} was accepted')
        node = shutil.which('node')
        if node is None:
            print('er-duel-rules-bans selftest: PASS (node absent: the agent did not read it back)')
            return 0
        probe = ("const A = require(process.argv[1]); const fs = require('fs');"
                 "const r = A.readConfig(fs.readFileSync(process.argv[2], 'utf8'));"
                 "console.log(JSON.stringify([r.problems, A.describeConfig(r.config)]));")
        done = subprocess.run([node, '-e', probe, str(AGENT), str(path)], capture_output=True,
                              text=True, timeout=20)
        # The probe prints exactly one line, so read only the last one. Whatever runs `node` may
        # print first: the proto shim writes "Detected an AI agent environment, printing as NDJSON"
        # to stdout on some invocations when AI_AGENT is set (measured 2026-10-19, which failed
        # this selftest in a pre-push run with `Extra data: line 2 column 1`).
        lines = [line for line in done.stdout.splitlines() if line.strip()]
        if not lines:
            raise AssertionError(f'node printed nothing; stderr: {done.stderr.strip()}')
        problems, described = json.loads(lines[-1])
        assert problems == [], problems
        assert described == ('48 of 49 built-in rules on (off: LightRoll), runeLevel=150, '
                             '2 of 3 bans of your own on'), described
    print('er-duel-rules-bans selftest: PASS')
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split('\n\n')[0],
                                 formatter_class=argparse.RawDescriptionHelpFormatter,
                                 epilog=__doc__.split('\n\n', 1)[1])
    ap.add_argument('--file', type=pathlib.Path, default=GAME_DIR / RULES_FILE_NAME)
    ap.add_argument('--selftest', action='store_true')
    ap.add_argument('command', nargs='*')
    a = ap.parse_args()
    if a.selftest:
        return selftest()
    if not a.command:
        ap.print_help()
        return 2
    print(run(a.command, a.file))
    return 0


if __name__ == '__main__':
    sys.exit(main())
